"""Exact feasible dual bounds for remaining flexible resource work.

For any nonnegative integer prices w, every completion obeys
 T >= ceil((sum_r w[r]*sum(append_only_calendars[r]) +
            sum_remaining_task min_legal_binding sum_r w[r]*work[b,r]) /
           sum_r w[r]*capacity[r]).

Bindings may differ in time and resources. Fractional/global consistency,
future mutual wiring conflicts and cache misses are relaxed, never invented.
Prices are generated by deterministic bottleneck responses on the declared
action profiles. Every price vector is valid independently of convergence.
This is a search bound; compiler memoization is not a hardware cache.
"""
from functools import lru_cache
import math


class WorkPriceBound:
    def __init__(self,conditional,tasks,hardware,*,rounds=12):
        if type(rounds)!=int or rounds<1:raise ValueError('positive work-price rounds required')
        self.conditional=conditional;self.hardware=hardware
        self.options=[];self.masks=[0]*len(conditional.resource_profiles)
        for i,t in enumerate(tasks):self.masks[conditional.resource_profile_for[t['id']]]|=1<<i
        self.full_counts=[mask.bit_count() for mask in self.masks]
        resources=set()
        for profile in conditional.resource_profiles:
            options=set()
            for alternative,terms in profile:
                demand={}
                for group,ticks in terms:
                    for resource in group:demand[resource]=demand.get(resource,0)+ticks
                option=tuple(sorted(demand.items()));options.add((alternative,option));resources.update(demand)
            self.options.append(tuple(sorted(options)))
        self.resources=tuple(sorted(resources));self.cache={};self.calls=0
        self.prices=[]
        if not resources:return
        capacities={r:hardware['resources'][r] for r in self.resources}
        if any(type(c)!=int or c<1 for c in capacities.values()):raise ValueError('invalid work-price capacity')
        common=math.lcm(*capacities.values());votes={r:1 for r in self.resources};seen=set()
        legal=[[(i,d) for i,d in profile if conditional.possible(conditional.alternatives[i])]
               for profile in self.options]
        for step in range(rounds):
            weights=tuple((r,votes[r]*(common//capacities[r])) for r in self.resources)
            divisor=math.gcd(*(value for _,value in weights))
            weights=tuple((r,value//divisor) for r,value in weights)
            if weights not in seen:self.prices.append(weights);seen.add(weights)
            w=dict(weights);loads={r:0 for r in self.resources}
            for count,profile in zip(self.full_counts,legal):
                if not profile:continue
                _,demand=min(profile,key=lambda x:(sum(w[r]*t for r,t in x[1]),x))
                for r,t in demand:loads[r]+=count*t
            # Compare load/capacity with integer cross products, no floating
            # LP objective or tolerance can turn this into an invalid bound.
            bottleneck=self.resources[0]
            for r in self.resources[1:]:
                if loads[r]*capacities[bottleneck]>loads[bottleneck]*capacities[r]:bottleneck=r
            votes[bottleneck]+=max(1,sum(votes.values())//(step+1))
        self.denominators=[sum(value*capacities[r] for r,value in w) for w in self.prices]
        self._remaining=lru_cache(maxsize=512)(self._remaining_counts)

    def _remaining_counts(self,done):
        return tuple(full-(done&mask).bit_count() for full,mask in zip(self.full_counts,self.masks))

    def table(self,nets):
        nets=frozenset(nets)
        if nets not in self.cache:
            legal=[[(i,d) for i,d in p if self.conditional.possible(nets|self.conditional.alternatives[i])]
                   for p in self.options]
            rows=[]
            for weights in self.prices:
                w=dict(weights)
                rows.append(tuple(min((sum(w[r]*t for r,t in d) for _,d in profile),default=None)
                                  for profile in legal))
            self.cache[nets]=rows
        return self.cache[nets]

    def get(self,state):
        self.calls+=1
        if not self.resources:return state.makespan
        remaining=self._remaining(state.done);best=state.makespan
        calendars={r:sum(state.resources[r]) for r in self.resources}
        for r,intervals in getattr(state,'windows',{}).items():
            if r in calendars:calendars[r]=sum(b-a for a,b in intervals)
        for weights,denominator,profile_costs in zip(self.prices,self.denominators,self.table(state.nets)):
            numerator=sum(weight*calendars[r] for r,weight in weights)
            for count,cost in zip(remaining,profile_costs):
                if count:
                    if cost is None:return None
                    numerator+=count*cost
            best=max(best,(numerator+denominator-1)//denominator)
        return best

    def statistics(self):
        return {'prices':len(self.prices),'profiles':len(self.options),'net_unions':len(self.cache),
                'rank_calls':self.calls,'scope':'exact integer feasible-dual workload bounds; no optimality guarantee'}
