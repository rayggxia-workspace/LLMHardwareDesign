"""Generate original Q16.16 coefficients with Decimal(precision=60), RNE.

This generates coefficients, not claims of measured RTL/model accuracy.
The independent floating-reference scan and RTL test must run separately.
"""
import argparse
from decimal import Decimal,localcontext,ROUND_HALF_EVEN
import hashlib,json
from pathlib import Path


def generate(destination):
    tables=[]
    with localcontext() as ctx:
        ctx.prec=60
        one=Decimal(1);two=Decimal(2)
        pi=Decimal('3.14159265358979323846264338327950288419716939937510582097494')
        c=(two/pi).sqrt()
        for fn,name,lo,hi,step in [(0,'exp',-16,0,128),(1,'sigmoid',-8,8,32),(2,'silu',-8,8,32),(3,'gelu_tanh',-8,8,32),(4,'softplus',-16,16,32)]:
            values=[]
            for i in range((hi-lo)*step+1):
                x=Decimal(lo)+Decimal(i)/step
                if fn==0:y=x.exp()
                elif fn in (1,2):
                    y=one/(one+(-x).exp())
                    if fn==2:y*=x
                elif fn==3:
                    t=c*(x+Decimal('0.044715')*x*x*x)
                    e=(two*t).exp();y=x*(one+(e-one)/(e+one))/two
                else:y=(one+x.exp()).ln()
                values.append(int((y*65536).to_integral_value(rounding=ROUND_HALF_EVEN)))
            tables.append(dict(function=fn,name=name,domain=[lo,hi],segments_per_unit=step,values=values))
    lines=['// Generated by generate_vector_tables.py; Decimal60 RNE, original coefficients.',
           'function automatic signed [31:0] v_lut;', ' input [2:0] fn;input [11:0] index;', ' begin v_lut=0;case(fn)']
    for table in tables:
        lines.append('  3\'d%d:case(index)'%table['function'])
        for i,v in enumerate(table['values']):lines.append("   12'd%d:v_lut=%s32'sd%d;"%(i,'-' if v<0 else '',abs(v)))
        lines.append('   default:v_lut=0;endcase')
    lines+=['  default:v_lut=0;endcase end','endfunction','']
    data='\n'.join(lines).encode();destination.write_bytes(data)
    result=dict(schema='block-v1-vector-coefficients/1',format='S32 Q16.16',generation='Decimal60 RNE',
                include_sha256=hashlib.sha256(data).hexdigest(),tables=tables,rtl_accuracy_verified=False)
    destination.with_suffix('.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')


if __name__=='__main__':
    p=argparse.ArgumentParser(__doc__);p.add_argument('destination',type=Path);a=p.parse_args();generate(a.destination)
