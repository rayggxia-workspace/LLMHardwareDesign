"""Generate a reviewable C8+T6K wrapper while preserving all baseline pins."""
import argparse
import hashlib
from pathlib import Path
import re


def generate(root):
    source = (root / "project/rtl/shared_gdn/shared109.sv").read_text(encoding="utf-8")
    header = re.search(r"module shared109\((.*?)\);", source, re.S).group(1)
    ports = []
    for item in header.split(","):
        name = re.findall(r"[a-zA-Z_]\w*", item)[-1]
        assert name not in ports
        ports.append(name)
    mapped = {name: name for name in ports}
    mapped.update(cmd="cmd && !transaction_busy", ack="ack && !transaction_busy",
                  cmd_ready="core_cmd_ready", cmd_accept="core_cmd_accept",
                  result_valid="core_result_valid", result_candidate="core_result_candidate",
                  result_index="core_result_index", result_data="core_result_data",
                  result_take="core_result_take")
    extra = """,
 input wire result_release, output wire result_release_ready,
 output wire [1:0] result_owner, output wire [31:0] result_generation,
 output wire [9:0] result_words,
 output wire transaction_busy, transaction_sealed, transaction_committed,
 output wire transaction_error, output wire [2:0] transaction_state"""
    text = "// Generated by make_wrapper.py; baseline source SHA256 " + hashlib.sha256(source.encode()).hexdigest() + "\n"
    text += "// Data result pins now expose committed T6K reads. DONE ACK is gated until release.\n"
    text += "module shared121(" + header.replace("output reg", "output wire") + extra + ");\n"
    text += """ wire core_cmd_ready, core_cmd_accept, core_result_valid, core_result_candidate, core_result_take;
 wire [9:0] core_result_index;
 wire [127:0] core_result_data;
 wire start_ready, write_ready, commit_ready, revoke_ready;
 wire revoke = abort_accept || (candidate_ready && reject_candidate) || (done && status != 0);
 wire [9:0] words = owner == 0 ? 10'd384 : owner == 1 ? 10'd256 : owner == 2 ? 10'd32 : 10'd128;
 assign cmd_ready = core_cmd_ready && !transaction_busy;
 assign cmd_accept = core_cmd_accept;
 assign core_result_take = write_ready;
 assign result_candidate = 1'b0;
 transaction6k sink(
  .clk(clk), .reset(reset),
  .begin_valid(core_result_valid && !transaction_busy), .begin_ready(start_ready),
  .begin_owner(owner), .begin_generation(epoch), .begin_words(words),
  .write_valid(core_result_valid), .write_ready(write_ready),
  .write_index(core_result_index), .write_data(core_result_data),
  .commit_valid(done && status == 0), .commit_ready(commit_ready),
  .revoke_valid(revoke), .revoke_ready(revoke_ready),
  .read_valid(result_valid), .read_take(result_take), .read_index(result_index),
  .read_data(result_data), .read_last(), .owner(result_owner), .generation(result_generation),
  .word_count(result_words), .release_valid(result_release), .release_ready(result_release_ready),
  .busy(transaction_busy), .sealed(transaction_sealed), .committed(transaction_committed),
  .protocol_error(transaction_error), .debug_state(transaction_state));
 shared109 core(
"""
    text += ",\n".join("  .%s(%s)" % (name, mapped[name]) for name in ports)
    text += ");\nendmodule\n"
    return text


if __name__ == "__main__":
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[3])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = args.root / "project/rtl/block_v1/shared121.sv"
    text = generate(args.root)
    if args.check:
        assert target.read_bytes() == text.encode(), "generated wrapper differs"
    else:
        target.write_bytes(text.encode())
    print("shared121 wrapper pins and generated bytes verified")
