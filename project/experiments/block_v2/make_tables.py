"""Generate bounded S16 function coefficients; no downloaded/unversioned LUTs."""
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def main():
    target = ROOT / 'project/rtl/block_v2/block_v2_g_tables.svh'
    rows = ['// Generated by project/experiments/block_v2/make_tables.py.',
            '// x:Q5.10; sigmoid:Q1.14, other results:Q5.10. Grid spacing 1/32.',
            'function automatic signed [15:0] activation_lut;',
            ' input [1:0] fn; input [10:0] index;',
            ' begin case({fn,index})']
    count = 0
    for fn in range(4):
        limit = 16 if fn == 3 else 8
        for i in range(limit * 64 + 1):
            x = -limit + i / 32
            if fn == 0:
                y = x / (1 + math.exp(-x))
            elif fn == 1:
                y = 1 / (1 + math.exp(-x))
            elif fn == 2:
                y = .5*x*(1+math.tanh(math.sqrt(2/math.pi)*(x+.044715*x*x*x)))
            else:
                y = math.log1p(math.exp(x))
            value = round(y * (16384 if fn == 1 else 1024))
            assert -32768 <= value <= 32767
            literal = f"-16'sd{-value}" if value < 0 else f"16'sd{value}"
            rows.append(f" 13'd{fn*2048+i}: activation_lut={literal};")
            count += 1
    rows += [" default:activation_lut=16'sd0;", ' endcase end', 'endfunction', '']
    target.write_text('\n'.join(rows), encoding='utf-8')
    print(json.dumps(dict(path=str(target),entries=count,coefficient_bits=16,
                         sha256=hashlib.sha256(target.read_bytes()).hexdigest())))
    target=target.with_name('block_v2_n_exp.svh')
    rows=['// EXP(x), x Q5.10 in [-16,0]; UQ1.15 samples at 1/64, RNE interpolation.',
          'function automatic [15:0] exp_lut;', ' input [10:0] index;', ' begin case(index)']
    for i in range(1025):
        rows.append(f"  11'd{i}:exp_lut=16'd{round(math.exp(-16+i/64)*32768)};")
    rows+=['  default:exp_lut=0;', ' endcase end', 'endfunction', '']
    target.write_text('\n'.join(rows),encoding='utf-8')


if __name__ == '__main__':
    main()
