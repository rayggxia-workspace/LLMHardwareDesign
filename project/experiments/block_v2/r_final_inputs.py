"""Freeze immutable R final data for independent computations before sealing.

Full native LEC must have started, so its input files are already written.
Nothing here treats an unfinished producer or these computations as acceptance.
"""
import json
from pathlib import Path


def capture(root,source,sha):
    source=source.resolve()
    assert source.parts[-2:]==('pnr','r') and source.parent.parent.name.isdigit()
    assert 'issue143-seven-block-v2-20261030' in source.parts
    flow=json.loads((source/'native-flow.json').read_text())
    assert flow['top']=='block_v1_r' and not flow['qualified_hard_macro']
    for name,digest in flow['rtl_sha256'].items():assert sha(root/name)==digest
    proof=source/'route-repair-proof.json'
    assert sha(proof)==flow['postroute_repair']['proof_sha256']
    repaired=json.loads(proof.read_text())
    assert repaired['passed'] and repaired['computation_only'] and not repaired['native_whole_drc_zero']
    assert repaired['kind']=='single-combinational-buffer-master' and repaired['computation_admission']['unresolved_native_drc_count']==822
    relative=Path('flow/results/nangate45/bv1_block_v1_r/base')
    log=source/'flow/logs/nangate45/bv1_block_v1_r/base/6_final_lec_check.log'
    assert log.is_file() and log.stat().st_size>0,'Final files are not known stable before native LEC starts'
    parent_status='native-full-LEC-pending'
    if (source/'receipt.json').exists():
        receipt=json.loads((source/'receipt.json').read_text());assert receipt['passed']
        assert flow['passed'] and flow['pipeline_completed'];parent_status='native-producer-completed'
    fixed={}
    # SPEF is generated by a later native stage or the separate fresh-RC job;
    # neither native geometry nor GDS consumes it. Do not pretend it exists.
    for name in ('6_final.odb','6_final.def','6_final.v','6_final.sdc'):
        path=source/relative/name;assert path.is_file() and path.stat().st_size>0
        fixed[str(relative/name)]=dict(path=str(path),sha256=sha(path),bytes=path.stat().st_size)
    for name in ('config.mk','pins.json','pins.tcl','input.sdc','route-repair-proof.json'):
        path=source/name;fixed[name]=dict(path=str(path),sha256=sha(path),bytes=path.stat().st_size)
    assert fixed['config.mk']['sha256']==flow['config_sha256']
    assert fixed['pins.json']['sha256']==flow['pins_sha256']
    return dict(passed=True,qualified=False,native_leaf_accepted=False,raw_source=str(source),
                top=flow['top'],rtl_sha256=flow['rtl_sha256'],fixed_files=fixed,
                parent_status_at_capture=parent_status,
                scope='Stable exact final files for independent computation; unfinished native proof is not accepted. Joining requires actual producer pass and identical files, with the explicit approved-SDC sealing policy.')
