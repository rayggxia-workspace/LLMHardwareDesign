module tb_native_joint_drain;
    logic clk = 0;
    logic reset = 1;
    logic admission_closed = 1, switch_idle = 1, dma_transport_quiescent = 1;
    logic [2:0] p_idle = '1, p_window_idle = '1, p_copy_ack_drained = '1;
    logic [5:0] local_link_drained = '1;
    logic relay_queues_empty = 1;
    logic [3:0] ddr_queues_empty = '1;
    logic ddr_request_pending = 0, ddr_response_pending = 0;
    logic purge_request_fire = 0, purge_response_fire = 0;
    logic [31:0] purge_request_generation = 0, purge_response_generation = 0;
    logic [31:0] current_dma_generation = 1;
    wire transport_drained;
    native_joint_drain dut (.*);

    task automatic check(input bit expected);
        #1;
        if (transport_drained !== expected) $fatal(1, "bad joint drain expected=%0d got=%0d", expected, transport_drained);
    endtask
    task automatic tick;
        #1 clk = 1;
        #1 clk = 0;
    endtask

    initial begin
        tick();
        reset = 0;
        check(0);
        purge_response_generation = 1;
        purge_response_fire = 1;
        tick();
        purge_response_fire = 0;
        check(0);
        purge_request_generation = 2;
        purge_request_fire = 1;
        check(0);
        tick();
        purge_request_fire = 0;
        check(0);
        purge_response_fire = 1;
        tick();
        purge_response_fire = 0;
        check(0);
        purge_response_generation = 2;
        purge_response_fire = 1;
        tick();
        purge_response_fire = 0;
        check(0);
        current_dma_generation = 2;
        check(1);
        admission_closed = 0;
        check(0);
        admission_closed = 1;
        switch_idle = 0;
        check(0);
        switch_idle = 1;
        dma_transport_quiescent = 0;
        check(0);
        dma_transport_quiescent = 1;
        p_idle[2] = 0;
        check(0);
        p_idle[2] = 1;
        p_window_idle[1] = 0;
        check(0);
        p_window_idle[1] = 1;
        p_copy_ack_drained[0] = 0;
        check(0);
        p_copy_ack_drained[0] = 1;
        local_link_drained[5] = 0;
        check(0);
        local_link_drained[5] = 1;
        relay_queues_empty = 0;
        check(0);
        relay_queues_empty = 1;
        ddr_queues_empty[3] = 0;
        check(0);
        ddr_queues_empty[3] = 1;
        ddr_request_pending = 1;
        check(0);
        ddr_request_pending = 0;
        ddr_response_pending = 1;
        check(0);
        ddr_response_pending = 0;
        check(1);
        purge_request_fire = 1;
        purge_request_generation = 3;
        check(0);
        tick();
        purge_request_fire = 0;
        check(0);
        purge_response_fire = 1;
        purge_response_generation = 3;
        current_dma_generation = 3;
        check(0);
        tick();
        purge_response_fire = 0;
        check(1);
        reset = 1;
        check(0);
        tick();
        reset = 0;
        check(0);
        $display("PASS native joint drain cold boot, stale ACK, re-arm and independent owner backpressure");
        $finish;
    end
endmodule
