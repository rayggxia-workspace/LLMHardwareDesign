#!/usr/bin/env python3
"""Copy coefficient integers from pinned RTL; never regenerate via host libm.
These coefficients are shared source data, not an independent numerical oracle.
"""
# 本脚本只导入既有RTL表的整数，不使用本机exp/tanh重算，避免不同libm造成系数漂移。
from pathlib import Path
import hashlib, json, re, subprocess, argparse
# 从tools/向上3级到仓库根；输出是可直接编译的头文件，不要求仿真时读取RTL。
ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / 'project/systemc/include/blocks/tables.hpp'
def render():
    """返回UTF-8/LF头文件文本；生成的说明与系数一起受--check校验。"""
    # 分别读取G四激活表与N的EXP表，保留它们各自不同的输入域和输出Q格式。
    g=(ROOT/'project/rtl/block_v2/block_v2_g_tables.svh').read_text()
    n=(ROOT/'project/rtl/block_v2/block_v2_n_exp.svh').read_text()
    # G的case键为(fn<<11)|index；正则同时保留负表项的符号。
    entries={int(key):(-1 if sign else 1)*int(val) for key,sign,val in re.findall(r"13'd(\d+): activation_lut=(-?)16'sd(\d+);",g)}
    exp={int(key):int(val) for key,val in re.findall(r"11'd(\d+):exp_lut=16'd(\d+);",n)}
    # 前三函数有效513点，Softplus有效1025点；C++统一行宽1025，其余项由语言规则补零。
    arrays=[[entries[(f<<11)+i] for i in range(1025 if f==3 else 513)] for f in range(4)]
    assert len(exp)==1025
    # 头文件中的注释也由生成器维护，禁止只编辑产物导致下次生成丢失说明。
    lines=['/**', ' * 定点系数数据：由tools/import_tables.py从冻结RTL表导入，不能将共享表当成独立数值真值。', ' * activation按函数号和网格索引寻址，表项是函数输出的原始S16编码。', ' * exp是N的UQ1.15指数表，输入差值Q5.10，固定[-16,0]域。', ' * 这些C++数组是主机参考数据，不能据其布局推断硬件使用SRAM或独立多端口ROM。', ' */', '// Generated by tools/import_tables.py from pinned RTL coefficients.', '#pragma once','#include <array>','#include <cstdint>','namespace blocks { namespace table {','inline constexpr int16_t activation[4][1025] = {']
    descriptions=['SiLU：x=-8+i/32，i=0..512，输出Q5.10；其余隐式补零项不可作为有效函数样本。', 'Sigmoid：x=-8+i/32，i=0..512，输出Q1.14；1.0编码16384。', 'GELU_tanh：x=-8+i/32，i=0..512，输出Q5.10。', 'Softplus：x=-16+i/32，i=0..1024，输出Q5.10。']
    for a,description in zip(arrays,descriptions):
        lines.append('// '+description)
        lines.append('{')
        lines += [','.join(map(str,a[i:i+16]))+',' for i in range(0,len(a),16)]
        lines.append('},')
    lines+=['};','// exp[i]对应EXP(-16+i/64)，i=0..1024；32768编码1.0。', '// 运行时由N对相邻表项的增量插值并RNE；域外策略在n.hpp中处理。','inline constexpr uint16_t exp[1025] = {']
    e=[exp[i] for i in range(1025)]
    lines += [','.join(map(str,e[i:i+16]))+',' for i in range(0,len(e),16)]
    lines+=['};','} }','']
    return '\n'.join(lines)
# 默认写入产物；--check只比较，不修改源或输出，供CTest/审查使用。
if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    content=render()
    if args.check:
        assert OUT.read_text()==content, 'tables differ from checked-in RTL'
        print('PASS: coefficient arrays match RTL source')
    else: OUT.write_text(content,encoding='utf-8')
