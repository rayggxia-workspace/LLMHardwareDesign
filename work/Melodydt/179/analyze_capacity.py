"""Reproduce PR176 packed-payload bounds; no RTL, scheduling or physical qualification."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
INPUT = ROOT / "work/Melodydt/179/capacity-input.json"
OUTPUT = ROOT / "docs/local-blocks/continuation-capacity.json"

def sha(data):
    return hashlib.sha256(data).hexdigest()

def analyze():
    raw = INPUT.read_bytes()
    data = json.loads(raw)
    if data["schema"] != "local-block-capacity-input/1":
        raise ValueError("Unsupported input schema")
    cases = []
    seen = set()
    for case in data["cases"]:
        if case["id"] in seen or case["capacity_bytes"] <= 0:
            raise ValueError("Invalid case or duplicate ID")
        seen.add(case["id"])
        objects = []
        for name, count, bits in case["objects"]:
            if type(count) is not int or count <= 0 or bits % 8 or bits <= 0:
                raise ValueError("Only positive byte-aligned payload objects are supported")
            objects.append(dict(name=name, elements=count, bits=bits, bytes=count * bits // 8))
        used = sum(row["bytes"] for row in objects)
        remaining = case["capacity_bytes"] - used
        cases.append(dict(id=case["id"], capacity_bytes=case["capacity_bytes"],
                          payload_bytes=used, remaining_bytes=remaining,
                          payload_status="exceeds" if remaining < 0 else
                          "exact" if remaining == 0 else "headroom",
                          objects=objects, assumption=case["assumption"],
                          execution_qualified=False))
    pool = data["resource_pool"]
    count = sum(pool["counts"].values())
    result = dict(schema="local-block-capacity-result/1", source_commit=data["source_commit"],
                  source_path=data["source_path"], input_sha256=sha(raw),
                  analyzer_sha256=sha(Path(__file__).read_bytes()),
                  accounting=data["accounting"], cases=cases,
                  pool=dict(block_count=count,
                            candidate_s_bytes=sum(n * pool["s_bytes"][k] for k,n in pool["counts"].items()),
                            current_s_bytes=count * pool["current_s_bytes_per_instance"],
                            t_bytes=pool["t_instances"] * pool["t_bytes_per_instance"]),
                  external_state_payload_bytes=data["external_state_payload_bytes"],
                  rtl_tested=False, schedule_verified=False, physical_qualified=False)
    return (json.dumps(result, ensure_ascii=False, indent=2) + "\n").encode("utf-8")

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare generated bytes with the checked-in result")
    args = parser.parse_args()
    expected = analyze()
    if args.check:
        if OUTPUT.read_bytes() != expected:
            raise SystemExit("FAIL: stored capacity result differs from recomputation")
        print("PASS: 8 packed-payload cases and resource-pool accounting reproduce exactly; no execution qualification.")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(expected)
        print("Wrote " + str(OUTPUT))

if __name__ == "__main__":
    main()
