"""Repair activity pin names while reusing verified mapped nets and RTL traces."""
import json
from pathlib import Path
import re
import subprocess
import sys

from retained_pin_activity import digest, map_retained
from dma_synth_power import LIB, SPECS
from control_gap_calibration import power


def main():
    source, out = map(Path, sys.argv[1:3]); kind = sys.argv[3]
    out.mkdir()
    calibration = source/'calibration.json'
    manifest = (source/'results.sha256').read_text()
    assert digest(calibration)+'  calibration.json' in manifest
    data = json.loads(calibration.read_text())
    if kind == 'dma':
        variant = data['variant']; rel, top, expected = SPECS[variant]
        root = source.parent.parent
        net = root/rel/'flow/results/nangate45'/top/'base/1_2_yosys.v'
        assert digest(net) == expected
        cases = [(name, source/name/'mapped-state-300.vcd', source/name/'power.tcl')
                 for name in data['windows']]
    else:
        top = 'conv4_q24' if kind == 'conv4' else 'special_lut_q24'
        net = source/'mapped-sta.v'
        cases = []
        for name, row in data['cases' if kind == 'conv4' else 'primitives'].items():
            for state in ('active', 'idle'):
                wave = source/(name+'-'+state+'.vcd' if kind == 'conv4' else '%d-%s.vcd'%(row['opcode'], state))
                cases.append((name+'-'+state, wave, source/(name+'-'+state)/'power.tcl'))
    # Re-read the exact structural Verilog used by STA: pre-write Yosys JSON
    # can have different autogenerated cell names and is not an alias map.
    ys = 'read_liberty -lib '+str(LIB)+'\nread_verilog '+str(net)+'\nhierarchy -top '+top+'\nwrite_json '+str(out/'mapped-graph.json')+'\n'
    (out/'graph.ys').write_text(ys)
    with (out/'graph.log').open('w') as f:
        subprocess.run(['yosys', '-Q', '-s', str(out/'graph.ys')], stdout=f, stderr=subprocess.STDOUT, check=True)
    corrected = {}; same = None
    for name, raw, original_tcl in cases:
        dest = out/(name+'.vcd')
        mapping = map_retained(raw, out/'mapped-graph.json', dest, top)
        if same is None: same = mapping['observed_pin_set_sha256']
        assert same == mapping['observed_pin_set_sha256'], 'unpaired activity coverage'
        tcl = original_tcl.read_text().replace(str(raw), str(dest))
        assert str(dest) in tcl
        p = power(tcl, out/name, mapping['expected_annotated_pins'])
        assert p['annotated'] == mapping['expected_annotated_pins'], 'incomplete exact pin annotation'
        p['activity_pin_mapping'] = mapping
        corrected[name] = p
        print('RETAINED_PIN_WINDOW_PASS', name, p['annotated'], flush=True)
    if kind == 'dma':
        for name, p in corrected.items(): data['windows'][name].update(p)
    else:
        for name, row in data['cases' if kind == 'conv4' else 'primitives'].items():
            row['power'] = {s:corrected[name+'-'+s] for s in ('active', 'idle')}
            duration = row['last']-row['first']
            count = row['channels'] if kind == 'conv4' else row['calls']
            energy = (row['power']['active']['power_w']['total']-row['power']['idle']['power_w']['total'])*duration/1000/count
            assert energy >= 0, 'negative paired dynamic energy'
            row['incremental_nj_per_channel' if kind == 'conv4' else 'incremental_nj_per_call'] = energy
    data['activity'] = 'Observed RTL nets aliased by exact structural connectivity to mapped pins; full declared pin set accepted by STA; unobserved internal nets propagated, not gate replay'
    data['pin_activity_source'] = dict(directory=str(source), calibration_sha256=digest(calibration),
        mapped_netlist_sha256=digest(net), graph_sha256=digest(out/'mapped-graph.json'),
        mapper_sha256=digest(Path(__file__).with_name('retained_pin_activity.py')),
        script_sha256=digest(__file__), same_pin_set_for_all_windows=True)
    (out/'calibration.json').write_text(json.dumps(data,indent=2)+'\n')
    print('RETAINED_PIN_CALIBRATION_PASS', kind, flush=True)


if __name__ == '__main__': main()
